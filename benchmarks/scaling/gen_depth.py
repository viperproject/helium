#!/usr/bin/env python3
"""Generate depth x block-length benchmark sources.

    python3 gen_depth.py            # writes src/depth_d{D}_m{M}.rs for the grid below

Two independent axes, so a measurement can attribute cost to one of them:

  D = nesting depth   -> how long a leaf block's path condition is, i.e. how much a
                         dominator-scoped scratch could inherit along a chain
  M = statements/block -> how much a single block accumulates before its obligations

Emits spec-less Rust (no prusti_contracts), no loops, no recursion, no returned
references -- the `../rust/` corpus rules, which this family was written under.
Encode with `python3 tools/bench/encode.py scaling`.

Nesting K deep gives K+1 paths; `gen_seq_if.py` puts K branches in sequence instead
(2^K paths). Companion to `gen_enum.py`, which scales payload enums.
"""

import pathlib

DEPTHS = [2, 4, 6, 8]
LENGTHS = [5, 20, 40]

HEADER = """//! GENERATED by benchmarks/scaling/gen_depth.py -- do not edit by hand.
//!
//! Nesting depth {d}, {m} statements per block. Spec-less Rust; obligations come
//! from Prusti's type predicates. No loops, no recursion, no returned references.

pub struct Cell {{
    pub v: i32,
    pub w: i32,
}}

pub struct Grid {{
    pub a: Cell,
    pub b: Cell,
    pub c: Cell,
}}

pub fn cell_new(v: i32, w: i32) -> Cell {{
    Cell {{ v, w }}
}}

pub fn cell_sum(c: &Cell) -> i32 {{
    c.v + c.w
}}

pub fn grid_sum(g: &Grid) -> i32 {{
    cell_sum(&g.a) + cell_sum(&g.b) + cell_sum(&g.c)
}}
"""


def straight_line(m, indent, var):
    """M statements of real arithmetic over the accumulator, no branching."""
    pad = " " * indent
    out = []
    for i in range(m):
        if i % 4 == 0:
            out.append(f"{pad}{var} = {var} + {i + 1};")
        elif i % 4 == 1:
            out.append(f"{pad}{var} = {var} * 2 - {i};")
        elif i % 4 == 2:
            out.append(f"{pad}{var} = {var} + g.a.v - g.b.w;")
        else:
            out.append(f"{pad}{var} = {var} + cell_sum(&g.c);")
    return "\n".join(out)


def nest(d, m, level, indent, var="acc"):
    """Nested if/else, each level adding one literal to the cube; the leaf carries the
    straight-line body, so the deepest block is also the longest.

    Only the `then` arm recurses — the `else` arm is a single statement. Recursing on
    both would duplicate the leaf body 2^d times, making the *source* exponential in
    the depth axis and confounding it with the length axis."""
    pad = " " * indent
    if level == d:
        return straight_line(m, indent, var)
    inner = nest(d, m, level + 1, indent + 4, var)
    return (
        f"{pad}if {level} * k < g.a.v + {level} {{\n"
        f"{inner}\n"
        f"{pad}    {var} = {var} + {level + 1};\n"
        f"{pad}}} else {{\n"
        f"{pad}    {var} = {var} - {level + 1};\n"
        f"{pad}}}"
    )


def emit(d, m):
    body = nest(d, m, 0, 4)
    # A second member with the same nesting but a `&mut` receiver, so the depth axis
    # is exercised with permission traffic too, not only pure arithmetic.
    mut_body = nest(d, min(m, 10), 0, 4, var="g.b.v")
    return f"""{HEADER.format(d=d, m=m)}
pub fn deep_eval(g: &Grid, k: i32) -> i32 {{
    let mut acc = grid_sum(g);
{body}
    acc
}}

pub fn deep_mutate(g: &mut Grid, k: i32) {{
{mut_body}
}}

pub fn deep_compare(g: &Grid, k: i32) -> i32 {{
    let x = deep_eval(g, k);
    let y = deep_eval(g, k + 1);
    if x < y {{
        y - x
    }} else {{
        x - y
    }}
}}
"""


def main():
    src = pathlib.Path(__file__).parent / "src"
    src.mkdir(parents=True, exist_ok=True)
    for d in DEPTHS:
        for m in LENGTHS:
            path = src / f"depth_d{d}_m{m}.rs"
            path.write_text(emit(d, m))
            print(f"wrote {path} ({len(path.read_text().splitlines())} lines)")


if __name__ == "__main__":
    main()
