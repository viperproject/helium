"""Shared helpers for the benchmarks/scaling/ generators.

Every generator follows the `../rust/gen_depth.py` pattern: one knob varies,
everything else is held fixed, so a timing change can be attributed to that
knob. Sources are spec-less Rust (no `prusti_contracts`): obligations come from
Prusti's own type predicates. Unlike `../rust/`, loops are allowed here. Still
no recursion, no returned references, no arrays or `panic!` (those pull in
Prusti prelude declarations this verifier cannot lower yet; see
`../panic_free/README.md`).
"""

import pathlib
import sys

SRC = pathlib.Path(__file__).parent / "src"

CELL = """
pub struct Cell {
    pub v: i32,
    pub w: i32,
}
"""


def header(generator, what):
    return (
        f"//! GENERATED by benchmarks/scaling/{generator} -- do not edit by hand.\n"
        f"//!\n"
        f"//! {what}\n"
        f"//! Spec-less Rust; obligations come from Prusti's type predicates.\n"
    )


def write(stem, text):
    SRC.mkdir(parents=True, exist_ok=True)
    path = SRC / f"{stem}.rs"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote src/{stem}.rs ({len(text.splitlines())} lines)", file=sys.stderr)


def indent(lines, n):
    pad = " " * n
    return "\n".join(pad + line if line else line for line in "\n".join(lines).split("\n"))
