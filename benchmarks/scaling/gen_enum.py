#!/usr/bin/env python3
"""Generate payload-enum benchmark sources over two independent axes.

    python3 gen_enum.py             # writes src/enum_v{N}_p{D}.rs for the grid below

`../rust/shape_area` is the one corpus program where we lose to Silicon, and it differs from
the cheap payload-enum programs (`structs_enums`, `inventory`) along *two* axes at
once — it has more variants AND deeper payloads. This separates them:

  N = variants        -> how deep the snapshot tower is that `p_E_snap`'s ternary
                         builds, hence how far a gate split must telescope to decide
                         `discr == cons(k)`
  D = payload depth   -> how much nested struct sits under each arm, hence how much
                         footprint one arm's `acc(p_E_k_owned(..))` actually covers

The cost we are chasing is the conditional footprint: `p_E`'s body is
`discr == cons(k) ==> acc(p_E_k_owned(snap))`, so unfolding mints an amount
`ite(discr == cons(k), 1/1, 0)` that `sufficient_leaf` has to case-split when the
path condition cannot decide the gate. Writing through a `&mut` payload is what
breaks that link (a `make_generic`/`make_concrete` round-trip havocs the chunk), so
every file's `e_grow` does exactly that, once per arm.

Spec-less Rust (no prusti_contracts), no loops, no recursion, no returned references
-- the `../rust/` corpus rules, which this family was written under. Encode with
`python3 tools/bench/encode.py scaling`.

Companion to `gen_depth.py`, which scales nesting depth x block length instead. The
payload-free version (variant count alone, up to 128) is `gen_enums.py`'s `enum_tag`.
"""

import pathlib

VARIANTS = [2, 3, 5, 8]
PAYLOAD_DEPTHS = [1, 2, 3]

HEADER = """//! GENERATED by benchmarks/scaling/gen_enum.py -- do not edit by hand.
//!
//! {n} payload variants, payload nesting depth {d}. Spec-less Rust; obligations come
//! from Prusti's type predicates. No loops, no recursion, no returned references.
//!
//! `e_grow` writes through a `&mut` payload once per arm -- the shape that makes the
//! conditional footprint's gate undecidable from the path condition.
"""


def payload_types(d):
    """Nested struct chain: L0 is two ints, L{i} is two L{i-1}."""
    out = ["pub struct L0 {\n    pub x: i32,\n    pub y: i32,\n}\n"]
    for i in range(1, d):
        out.append(f"pub struct L{i} {{\n    pub a: L{i - 1},\n    pub b: L{i - 1},\n}}\n")
    return "\n".join(out)


def leaf_path(d, base):
    """Path from a depth-`d` payload down to one leaf int field."""
    return base + ".a" * (d - 1) + ".x"


def other_leaf_path(d, base):
    return base + ".a" * (d - 1) + ".y"


def enum_decl(n, d):
    top = f"L{d - 1}"
    arms = "\n".join(f"    V{i}({top})," for i in range(n))
    return f"pub enum E {{\n{arms}\n}}\n"


def fn_grow(n, d):
    """Match every arm and write through the payload -- the &mut round trip."""
    out = ["pub fn e_grow(e: &mut E, k: i32) {", "    match e {"]
    for i in range(n):
        lx, ly = leaf_path(d, "p"), other_leaf_path(d, "p")
        out.append(f"        E::V{i}(p) => {{")
        out.append(f"            {lx} = {lx} * k + {i};")
        out.append(f"            {ly} = {ly} + {lx};")
        out.append("        }")
    out += ["    }", "}"]
    return "\n".join(out)


def fn_read(n, d):
    out = ["pub fn e_read(e: &E) -> i32 {", "    match e {"]
    for i in range(n):
        out.append(f"        E::V{i}(p) => {leaf_path(d, 'p')} + {other_leaf_path(d, 'p')},")
    out += ["    }", "}"]
    return "\n".join(out)


def fn_tag(n):
    out = ["pub fn e_tag(e: &E) -> i32 {", "    match e {"]
    for i in range(n):
        out.append(f"        E::V{i}(_) => {i},")
    out += ["    }", "}"]
    return "\n".join(out)


def fn_guarded(n, d):
    """One arm's write under a further condition: a cube suffix on top of the arm."""
    out = ["pub fn e_guarded(e: &mut E, k: i32, up: bool) {", "    match e {"]
    for i in range(n):
        lx = leaf_path(d, "p")
        out.append(f"        E::V{i}(p) => {{")
        out.append("            if up {")
        out.append(f"                {lx} = {lx} + k;")
        out.append("            } else {")
        out.append(f"                {lx} = {lx} - k;")
        out.append("            }")
        out.append("        }")
    out += ["    }", "}"]
    return "\n".join(out)


def source(n, d):
    parts = [
        HEADER.format(n=n, d=d),
        payload_types(d),
        enum_decl(n, d),
        fn_tag(n),
        fn_read(n, d),
        fn_grow(n, d),
        fn_guarded(n, d),
    ]
    return "\n".join(parts) + "\n"


def main():
    here = pathlib.Path(__file__).resolve().parent
    src = here / "src"
    src.mkdir(exist_ok=True)
    written = []
    for n in VARIANTS:
        for d in PAYLOAD_DEPTHS:
            path = src / f"enum_v{n}_p{d}.rs"
            path.write_text(source(n, d))
            written.append(path.name)
    print(f"wrote {len(written)} sources: {', '.join(written)}")


if __name__ == "__main__":
    main()
