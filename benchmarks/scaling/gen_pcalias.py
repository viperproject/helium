#!/usr/bin/env python3
"""Locations that coincide only under the path condition (Viper-only).

    python3 gen_pcalias.py      # writes vpr/pcalias_k{K}.vpr

  K = references holding a 1/K share of `f` each. Under a branch that makes
      them all equal to `x`, the permission to `x.f` is the sum of K chunks
      that are distinct locations off the branch. The branch gives `x.f` up
      in K exhales of 1/K each, every one drawing on what is left of the same
      K-chunk set, then takes the shares back.

Prusti does not produce this shape from safe Rust (references there never
alias), so the family is Viper-only: generated straight into `vpr/`, no `src/`.
"""

import pathlib
import sys

VPR = pathlib.Path(__file__).parent / "vpr"
SIZES = [2, 3, 4, 5, 6, 7, 8, 12, 16, 24, 32, 48, 64]


def emit(k):
    ys = [f"y{i}" for i in range(k)]
    params = ", ".join(["x: Ref"] + [f"{y}: Ref" for y in ys])
    shares = " && ".join(f"acc({y}.f, 1/{k})" for y in ys)
    equal = " && ".join(f"x == {y}" for y in ys)
    exhales = "\n".join(f"    exhale acc(x.f, 1/{k})" for _ in range(k))
    return f"""// GENERATED by benchmarks/scaling/gen_pcalias.py -- do not edit by hand.
//
// {k} chunks of `f` that coincide with `x` only under the branch condition;
// the branch gives `x.f` up in {k} exhales.

field f: Int

method run({params})
  requires {shares}
  ensures {shares}
{{
  if ({equal}) {{
{exhales}
    inhale {shares}
  }}
}}
"""


if __name__ == "__main__":
    VPR.mkdir(parents=True, exist_ok=True)
    for k in SIZES:
        text = emit(k)
        path = VPR / f"pcalias_k{k}.vpr"
        path.write_text(text, encoding="utf-8")
        print(f"wrote vpr/pcalias_k{k}.vpr ({len(text.splitlines())} lines)", file=sys.stderr)
